//
// STATUS: FIRST DRAFT, to be read and corrected by Wael before launch. The Arabic is
// the product; these were written to be clear and neutral, not to be final.
//
// VOICE (Oct 8): singular and direct, like waelwebdesign.com ("اطلب تصميم موقعك",
// "استكشف القوالب"), not the plural-formal "افحصوا / موقعكم" of the first draft. If you
// prefer the formal plural, it is a find-and-replace in this one file.
//
// CODE IN ARABIC TEXT. Wrap any code, tag or value in `backticks`. The report page
// shows each one as an isolated left-to-right chip, and the email isolates it too.
// Without that, Arabic's right-to-left rules SCRAMBLE a snippet like <meta name="viewport">
// (the same bidi bug as the chat's links, CLAUDE.md "Links in the bubbles"). Always
// backtick a snippet; never type one bare inside a sentence.
//
// Three rules for editing:
//   1. Say what was FOUND, not what it "means about the owner". A stranger is
//      reading a score about their own business.
//   2. "Likely" and "often" are honest; "will lose you customers" is not.
//   3. A fix says WHAT to change and WHERE, never "improve your site".

