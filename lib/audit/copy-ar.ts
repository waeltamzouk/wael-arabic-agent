const esc = (value: unknown) =>
  String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** Splits "text with `code` in it" into pieces, so a renderer can isolate the code. */
export function parts(text: string): { text: string; code: boolean }[] {
  return text.split(/`([^`]*)`/).map((piece, i) => ({ text: piece, code: i % 2 === 1 })).filter((p) => p.text !== "");
}

/** The same text with the backticks removed, for plain-text emails. */
export const plain = (text: string) => text.replace(/`/g, "");

